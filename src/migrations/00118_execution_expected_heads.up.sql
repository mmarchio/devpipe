-- P18-41 (WBS 18.50 / 18.51 / 18.62): the repository HEAD (and branch) an
-- execution expects, append-only: the latest row is the expectation; every
-- row records why it changed — bootstrap, an overseer checkpoint commit,
-- or an audited operator acceptance (ACCEPT_REPOSITORY_HEAD). Any other
-- HEAD / branch change stops new work.
CREATE TABLE IF NOT EXISTS execution_expected_heads (
	id UUID PRIMARY KEY,
	execution_id UUID NOT NULL,
	project_id UUID NOT NULL,
	seq INTEGER NOT NULL CHECK (seq > 0),
	head TEXT NOT NULL DEFAULT '',
	branch TEXT NOT NULL DEFAULT '',
	source TEXT NOT NULL CHECK (source IN ('BOOTSTRAP', 'FIRST_CHECK', 'CHECKPOINT', 'OPERATOR_ACCEPT')),
	checkpoint_id UUID NULL REFERENCES repository_checkpoints (id) ON DELETE SET NULL,
	actor TEXT NOT NULL DEFAULT '',
	reason TEXT NOT NULL DEFAULT '',
	recorded_at TIMESTAMPTZ NOT NULL,
	UNIQUE (execution_id, seq),
	FOREIGN KEY (execution_id, project_id) REFERENCES executions (id, project_id) ON DELETE CASCADE
);
DROP TRIGGER IF EXISTS execution_expected_heads_immutable ON execution_expected_heads;
CREATE TRIGGER execution_expected_heads_immutable BEFORE UPDATE ON execution_expected_heads
	FOR EACH ROW EXECUTE FUNCTION overseer_reject_update();

