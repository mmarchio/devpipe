-- P16-57 (WBS 16.81, 16.82): engine event types + a deterministic
-- per-execution sequence (assigned under the execution row lock; the
-- unique constraint rejects a duplicate).
ALTER TABLE execution_events ADD COLUMN IF NOT EXISTS exec_seq BIGINT NULL CHECK (exec_seq > 0);
ALTER TABLE execution_events DROP CONSTRAINT IF EXISTS execution_events_execution_seq_key;
ALTER TABLE execution_events ADD CONSTRAINT execution_events_execution_seq_key UNIQUE (execution_id, exec_seq);
ALTER TABLE execution_events DROP CONSTRAINT IF EXISTS execution_events_type_check;
ALTER TABLE execution_events ADD CONSTRAINT execution_events_type_check CHECK (type IN (
	'EXECUTION_BOOTSTRAP_REQUESTED', 'EXECUTION_READINESS_VALIDATED', 'EXECUTION_CONFIGURATION_SNAPSHOTTED',
	'EXECUTION_STATE_FILES_INITIALIZED', 'EXECUTION_RUNTIME_INITIALIZED', 'EXECUTION_CONTEXT_PREPARED',
	'EXECUTION_PROMPT_PREPARED', 'EXECUTION_BOOTSTRAP_COMPLETED', 'EXECUTION_BOOTSTRAP_FAILED', 'EXECUTION_STARTED',
	'EXECUTION_STEP_INTENT', 'EXECUTION_STEP_APPLIED', 'PLAN_ACTIVATED', 'PLAN_REJECTED', 'PLAN_AMENDED',
	'WORK_UNIT_CLAIMED', 'WORKER_DISPATCH_INTENT', 'VALIDATION_STARTED', 'VALIDATION_PASSED', 'VALIDATION_FAILED',
	'VALIDATION_INFRA_ERROR', 'FIX_ATTEMPT', 'CHECKPOINT_CREATED', 'CHECKPOINT_FAILED', 'CHECKPOINT_SKIPPED',
	'WORK_UNIT_DONE', 'PHASE_VALIDATION_FAILED', 'PHASE_DONE', 'EXECUTION_WAITING', 'EXECUTION_PAUSED',
	'EXECUTION_RESUMED', 'EXECUTION_CANCELLED', 'EXECUTION_RECOVERY_REQUIRED', 'EXECUTION_RECOVERY_RESOLVED',
	'HARDENING_STARTED', 'HARDENING_ANALYZED', 'HARDENING_OPERATION', 'HARDENING_GROUP_CONSOLIDATED',
	'HARDENING_GROUP_SKIPPED', 'HARDENING_COMPLETED', 'FINAL_VALIDATION_PASSED', 'FINAL_VALIDATION_FAILED',
	'PROJECT_COMPLETED'));
CREATE INDEX IF NOT EXISTS execution_events_timeline_idx ON execution_events (execution_id, exec_seq);
