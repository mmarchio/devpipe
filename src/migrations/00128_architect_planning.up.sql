-- Architect-led planning: the ARCHITECT writes the phase WBS as a markdown
-- file (ARCHITECT_DISPATCH, checked by WBS_VALIDATE), the PLANNER breaks it
-- into a markdown task file the overseer parses into the plan candidate.

-- Step actions.
DO $$
DECLARE c TEXT;
BEGIN
	FOR c IN
		SELECT con.conname FROM pg_constraint con
		JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
		WHERE con.conrelid = 'execution_steps'::regclass AND con.contype = 'c' AND att.attname = 'action'
	LOOP
		EXECUTE format('ALTER TABLE execution_steps DROP CONSTRAINT %I', c);
	END LOOP;
END $$;
ALTER TABLE execution_steps ADD CONSTRAINT execution_steps_action_check CHECK (action IN ('ARCHITECT_DISPATCH', 'WBS_VALIDATE',
	'PLAN_DISPATCH', 'PLAN_VALIDATE', 'SELECT_UNIT', 'DISPATCH', 'EVALUATE_RESULT',
	'CONTINUATION', 'RUN_UNIT_VALIDATION', 'UNIT_GATES', 'MORE_WORK', 'PHASE_VALIDATION', 'MORE_PHASES',
	'FINAL_HARDENING', 'HARDENING_FIX', 'FINAL_VALIDATION', 'FINAL_CHECKPOINT', 'CONTROL', 'COMPLETE'));

-- Engine event types: the architect's WBS accepted / rejected.
ALTER TABLE execution_events DROP CONSTRAINT IF EXISTS execution_events_type_check;
ALTER TABLE execution_events ADD CONSTRAINT execution_events_type_check CHECK (type IN (
	'EXECUTION_BOOTSTRAP_REQUESTED', 'EXECUTION_READINESS_VALIDATED', 'EXECUTION_CONFIGURATION_SNAPSHOTTED',
	'EXECUTION_STATE_FILES_INITIALIZED', 'EXECUTION_RUNTIME_INITIALIZED', 'EXECUTION_CONTEXT_PREPARED',
	'EXECUTION_PROMPT_PREPARED', 'EXECUTION_BOOTSTRAP_COMPLETED', 'EXECUTION_BOOTSTRAP_FAILED', 'EXECUTION_STARTED',
	'EXECUTION_STEP_INTENT', 'EXECUTION_STEP_APPLIED', 'PLAN_ACTIVATED', 'PLAN_REJECTED', 'PLAN_AMENDED',
	'WORK_UNIT_CLAIMED', 'WORKER_DISPATCH_INTENT', 'VALIDATION_STARTED', 'VALIDATION_PASSED', 'VALIDATION_FAILED',
	'VALIDATION_INFRA_ERROR', 'FIX_ATTEMPT', 'CHECKPOINT_CREATED', 'CHECKPOINT_FAILED', 'CHECKPOINT_SKIPPED',
	'WORK_UNIT_DONE', 'PHASE_VALIDATION_FAILED', 'PHASE_DONE', 'EXECUTION_WAITING', 'EXECUTION_PAUSED',
	'EXECUTION_RESUMED', 'EXECUTION_CANCELLED', 'EXECUTION_RECOVERY_REQUIRED', 'EXECUTION_RECOVERY_RESOLVED',
	'HARDENING_STARTED', 'HARDENING_ANALYZED', 'HARDENING_OPERATION', 'HARDENING_GROUP_CONSOLIDATED',
	'HARDENING_GROUP_SKIPPED', 'HARDENING_COMPLETED', 'FINAL_VALIDATION_PASSED', 'FINAL_VALIDATION_FAILED',
	'PROJECT_COMPLETED', 'REPOSITORY_HEAD_ACCEPTED', 'WORKER_RUN_REPOSITORY_EVIDENCE',
	'WBS_ACCEPTED', 'WBS_REJECTED'));

-- The planner's task file, stored verbatim with the candidate parsed from it.
ALTER TABLE plan_candidates ADD COLUMN IF NOT EXISTS markdown TEXT NULL;
