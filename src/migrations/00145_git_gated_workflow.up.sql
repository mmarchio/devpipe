-- The QA_TESTS_CHECK step action, and the GIT_FLOW expected-HEAD source
-- (each check constraint is replaced by column, whatever its name).
DO $$
DECLARE c TEXT;
BEGIN
	FOR c IN
		SELECT con.conname FROM pg_constraint con
		JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
		WHERE con.conrelid = 'execution_steps'::regclass AND con.contype = 'c' AND att.attname = 'action'
	LOOP
		EXECUTE format('ALTER TABLE execution_steps DROP CONSTRAINT %I', c);
	END LOOP;
	FOR c IN
		SELECT con.conname FROM pg_constraint con
		JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
		WHERE con.conrelid = 'execution_expected_heads'::regclass AND con.contype = 'c' AND att.attname = 'source'
	LOOP
		EXECUTE format('ALTER TABLE execution_expected_heads DROP CONSTRAINT %I', c);
	END LOOP;
END $$;
ALTER TABLE execution_steps ADD CONSTRAINT execution_steps_action_check CHECK (action IN (
	'COMMAND', 'IMPLEMENT_CHECK', 'TEST_CHECK', 'ACCEPTANCE_CHECK', 'QA_TESTS_CHECK', 'ARCHITECT_DISPATCH', 'WBS_VALIDATE',
	'PLAN_DISPATCH', 'PLAN_VALIDATE', 'SELECT_UNIT', 'DISPATCH', 'EVALUATE_RESULT',
	'CONTINUATION', 'RUN_UNIT_VALIDATION', 'UNIT_GATES', 'MORE_WORK', 'PHASE_VALIDATION', 'MORE_PHASES',
	'FINAL_HARDENING', 'HARDENING_FIX', 'FINAL_VALIDATION', 'FINAL_CHECKPOINT', 'CONTROL', 'COMPLETE'));
ALTER TABLE execution_expected_heads ADD CONSTRAINT execution_expected_heads_source_check
	CHECK (source IN ('BOOTSTRAP', 'FIRST_CHECK', 'CHECKPOINT', 'OPERATOR_ACCEPT', 'GIT_FLOW'));
