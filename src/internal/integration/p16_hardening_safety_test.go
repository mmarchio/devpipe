// TestP16171UnsafeCycleSkipped — WBS 16.171 / 16.177 / 16.105 / 16.91: the
// only duplicate group would create a → stringutil → b → a; it is skipped
// with the reason persisted, source and tests unchanged, hardening still
// completes (skipped-only). Generated code is never touched.
func TestP16171UnsafeCycleSkipped(t *testing.T) {
	gen := "// Code generated by hand; DO NOT EDIT.\n\npackage gen\n\nimport \"strings\"\n\nfunc normalizeName(s string) string {\n" + p16NormalizeBody + "}\n\nvar G = normalizeName\n"
	files := map[string]string{
		"go.mod":          "module ex\n\ngo 1.25\n",
		"a/a.go":          "package a\n\nimport \"strings\"\n\nconst Tag = \"!\"\n\nfunc normalizeName(s string) string {\n" + p16NormalizeBody + "}\n\nfunc A(s string) string { return normalizeName(s) }\n",
		"c/c.go":          "package c\n\nimport \"strings\"\n\nfunc normalizeName(s string) string {\n" + p16NormalizeBody + "}\n\nfunc C(s string) string { return normalizeName(s) }\n",
		"b/b.go":          "package b\n\nimport \"ex/a\"\n\nfunc Mark() string { return a.Tag }\n",
		"stringutil/s.go": "package stringutil\n\nimport \"ex/b\"\n\nfunc Exclaim(s string) string { return s + b.Mark() }\n",
		"a/a_test.go":     "package a\n\nimport \"testing\"\n\nfunc TestA(t *testing.T) {\n\tif A(\" X \") != \"x\" {\n\t\tt.Fatal()\n\t}\n}\n",
		"gen/gen.go":      gen,
		"vendor/v/v.go":   "package v\n",
	}
	delete(files, "vendor/v/v.go")
	r := p16HardeningRig(t, files, nil)
	r.runToHardening(t)
	r.runUntil(t, execution.StepCompleted, 200)
	for p, c := range files {
		if p == "go.mod" {
			continue
		}
		if r.read(t, p) != c {
			t.Fatalf("%s modified:\n%s", p, r.read(t, p))
		}
	}
	var cl, reason string
	if err := r.h.DBScan(t.Context(), `SELECT g.classification, g.reason FROM hardening_groups g JOIN hardening_passes p ON p.id = g.pass_id
		WHERE p.execution_id = '`+r.execID.String()+`'`, &cl, &reason); err != nil {
		t.Fatal(err)
	}
	if cl != "UNSAFE_IMPORT_CYCLE" || !strings.Contains(reason, "ex/a → ex/stringutil → ex/b → ex/a") {
		t.Fatalf("classification %s reason %q", cl, reason)
	}
	rep := r.report(t)
	for _, w := range []string{`"skipped_groups":1`, `"consolidated_groups":0`, `"import_cycle_failures":1`} {
		if !strings.Contains(rep, w) {
			t.Fatalf("report lacks %s: %s", w, rep)
		}
	}
	if n := r.count(t, "SELECT count(*) FROM hardening_retained_groups WHERE "+r.where()); n != 1 {
		t.Fatal("retained baseline not recorded")
	}
	if n := r.count(t, "SELECT count(*) FROM hardening_groups g JOIN hardening_passes p ON p.id = g.pass_id WHERE p.execution_id = '"+r.execID.String()+"' AND g.members::text LIKE '%ex/gen%'"); n != 0 {
		t.Fatal("generated code analysed")
	}
}

// TestP16172SimilarButDifferent — WBS 16.172 / 16.176: behaviourally
// different functions are not grouped; no duplicates → DONE immediately.
func TestP16172SimilarButDifferent(t *testing.T) {
	files := map[string]string{
		"go.mod": "module ex\n\ngo 1.25\n",
		"a/a.go": "package a\n\nimport \"strings\"\n\nfunc N(s string) string {\n" + p16NormalizeBody + "}\n",
		"b/b.go": "package b\n\nimport \"strings\"\n\nfunc N(s string) string {\n\ts = strings.TrimSpace(s)\n\ts = strings.ToLower(s)\n\treturn strings.ReplaceAll(s, \" \", \"_\")\n}\n",
	}
	r := p16HardeningRig(t, files, nil)
	r.runToHardening(t)
	r.runUntil(t, execution.StepCompleted, 200)
	rep := r.report(t)
	if !strings.Contains(rep, `"duplicate_groups":0`) || !strings.Contains(rep, `"termination":"FIXED_POINT"`) || !strings.Contains(rep, `"rounds":1`) {
		t.Fatalf("report %s", rep)
	}
	for p, c := range files {
		if r.read(t, p) != c {
			t.Fatalf("%s modified", p)
		}
	}
}

// TestP16173DomainOwned — WBS 16.173 / 16.102: duplicate domain logic in two
// high-level packages moves into the lower-level domain package, never a
// generic utility.
func TestP16173DomainOwned(t *testing.T) {
	body := "\ttotal := money.Amount(0)\n\tfor _, a := range xs {\n\t\ttotal += a\n\t}\n\treturn money.Round(total)\n"
	files := map[string]string{
		"go.mod":              "module ex\n\ngo 1.25\n",
		"money/money.go":      "package money\n\ntype Amount int64\n\nfunc Round(a Amount) Amount { return a / 100 * 100 }\n",
		"service/svc.go":      "package service\n\nimport \"ex/money\"\n\nfunc sum(xs []money.Amount) money.Amount {\n" + body + "}\n\nfunc Bill(xs []money.Amount) money.Amount { return sum(xs) }\n",
		"web/web.go":          "package web\n\nimport \"ex/money\"\n\nfunc sum(xs []money.Amount) money.Amount {\n" + body + "}\n\nfunc Show(xs []money.Amount) money.Amount { return sum(xs) }\n",
		"service/svc_test.go": "package service\n\nimport (\n\t\"testing\"\n\n\t\"ex/money\"\n)\n\nfunc TestBill(t *testing.T) {\n\tif Bill([]money.Amount{150, 250}) != 400 {\n\t\tt.Fatal()\n\t}\n}\n",
	}
	r := p16HardeningRig(t, files, func(h *hardening.Settings) { h.DomainPackages = []string{"money"} })
	r.runToHardening(t)
	r.runUntil(t, execution.StepCompleted, 300)
	var dest string
	if err := r.h.DBScan(t.Context(), `SELECT g.destination::text FROM hardening_groups g JOIN hardening_passes p ON p.id = g.pass_id
		WHERE p.execution_id = '`+r.execID.String()+`' AND g.status = 'CONSOLIDATED'`, &dest); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(dest, `"import_path": "ex/money"`) || !strings.Contains(dest, `"kind": "DOMAIN"`) {
		t.Fatalf("destination %s", dest)
	}
	if !strings.Contains(r.read(t, "money/sum.go"), "func Sum(") || strings.Contains(r.read(t, "web/web.go"), "func sum(") {
		t.Fatal("not consolidated into the domain package")
	}
}

// TestP16HardeningRounds — WBS 16.135–16.138, 16.178, 16.179.
func TestP16HardeningRounds(t *testing.T) {
	// Level k wraps level k-1; consolidating level k-1 makes the level-k
	// wrappers identical (they then call the same shared function).
	module := func(levels int) map[string]string {
		files := map[string]string{"go.mod": "module ex\n\ngo 1.25\n"}
		for _, pkg := range []string{"p", "q"} {
			src := "package " + pkg + "\n\nimport \"strings\"\n\nfunc normalizeName(s string) string {\n" + p16NormalizeBody + "}\n"
			prev := "normalizeName"
			for l := 1; l < levels; l++ {
				name := "wrap" + string(rune('A'+l-1))
				src += "\nfunc " + name + "(s string) string {\n\tv := " + prev + "(s)\n\treturn \"[\" + v + \"]\"\n}\n"
				prev = name
			}
			src += "\nfunc Use(s string) string { return " + prev + "(s) }\n"
			files[pkg+"/"+pkg+".go"] = src
		}
		return files
	}
	t.Run("round 1 exposes a duplicate, round 2 consolidates it, round 3 finds none", func(t *testing.T) {
		r := p16HardeningRig(t, module(2), nil)
		r.runToHardening(t)
		r.runUntil(t, execution.StepCompleted, 500)
		rep := r.report(t)
		for _, w := range []string{`"rounds":3`, `"consolidated_groups":2`, `"termination":"FIXED_POINT"`} {
			if !strings.Contains(rep, w) {
				t.Fatalf("report lacks %s: %s", w, rep)
			}
		}
	})
	t.Run("maximum rounds stop the loop and record remaining candidates", func(t *testing.T) {
		r := p16HardeningRig(t, module(4), func(h *hardening.Settings) { h.DuplicateFunctions.MaxRounds = 2 })
		r.runToHardening(t)
		r.runUntil(t, execution.StepCompleted, 500)
		rep := r.report(t)
		for _, w := range []string{`"termination":"MAX_ROUNDS"`, `"remaining_safe_groups":1`, `"consolidated_groups":2`, `"warning":"maximum hardening rounds reached`} {
			if !strings.Contains(rep, w) {
				t.Fatalf("report lacks %s: %s", w, rep)
			}
		}
	})
}
