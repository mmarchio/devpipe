// P8-12 (WBS 8.2): the 9 default prompt templates seeded as editable data at
// GLOBAL scope, idempotently, via a service-level op (no REST endpoint).
// The op is exercised over the harness pool with the transaction pool wired.
//
// State -> template key mapping (WBS 6.7 source: the non-empty
// PromptTemplate fields of service.defaultStateSpecs — the same table the
// P6-11 seed persists into workflow_states):
//
//	PHASE_PLAN        -> PLAN_PHASE
//	PLAN_VALIDATE     -> PLAN_VALIDATE
//	IMPLEMENT         -> IMPLEMENT_WORK_UNIT
//	VALIDATE          -> VALIDATE_WORK_UNIT
//	CONTINUE          -> CONTINUE_WORK_UNIT
//	FIX               -> FIX_WORK_UNIT
//	PHASE_VALIDATE    -> PHASE_VALIDATE
//
// The WBS 8.2 canonical default key set is the 9 keys seeded by
// service.DefaultTemplateKeys; PREPARE_WORK_UNIT and REVIEW_RESULT are
// seeded as editable data without a current default-state reference (the
// required-state set is the seven mappings above).

// p812Seeded is the number of global templates SeedDefaults creates (one
// v1 version each): every entry of service.defaultTemplateSpecs.
const p812Seeded = 25

// p812Service wires the seeding service over the harness pool.
func p812Service(t *testing.T, h *Harness) *service.PromptTemplateService {
	t.Helper()
	pool := h.App.DB().Raw()
	return service.NewPromptTemplateService(
		dbrepo.NewPromptTemplateRepository(pool),
		dbrepo.NewPromptTemplateVersionRepository(pool),
	).WithTxPool(pool)
}

// p812Signature is a full-row byte signature over the global prompt
// templates (T8.2.2/T8.2.5 non-mutation proof; row counts alone miss column
// mutations).
func p812Signature(t *testing.T, h *Harness, ctx context.Context) string {
	t.Helper()
	var sig string
	err := h.DBScan(ctx, `SELECT coalesce(string_agg(
			id || '|' || coalesce(project_id::text,'NULL') || '|' || key || '|' || name || '|'
			|| coalesce(description,'') || '|' || purpose || '|' || enabled || '|'
			|| version || '|' || created_at::text || '|' || updated_at::text,
		',' ORDER BY key), '') FROM prompt_templates WHERE project_id IS NULL`, &sig)
	if err != nil {
		t.Fatalf("global template signature: %v", err)
	}
	return sig
}

// T8.2.1 — Defaults seeded: the 9 WBS 8.2 keys exist at GLOBAL scope with
// distinct normalized keys, a known purpose from the 7 WBS values, and a v1
// content version each (content hash generated by P8-11).
func TestP812DefaultsSeeded(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	svc := p812Service(t, h)
	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("SeedDefaults: %v", err)
	}

	want := service.DefaultTemplateKeys
	if len(want) != 9 {
		t.Fatalf("DefaultTemplateKeys has %d keys, want the 9 WBS 8.2 defaults", len(want))
	}

	list, err := svc.ListGlobal(ctx)
	if err != nil {
		t.Fatalf("ListGlobal: %v", err)
	}
	// Seeded set = the 9 canonical keys, the two WBS 6.7 state-reference
	// aliases PLAN_VALIDATE/PHASE_VALIDATE (T8.2.3 resolves every reference)
	// and the remaining workflow templates (service.defaultTemplateSpecs).
	if len(list) != p812Seeded {
		t.Fatalf("global templates = %d, want %d", len(list), p812Seeded)
	}
	seen := map[string]bool{}
	for _, rec := range list {
		if rec.ProjectID != nil {
			t.Fatalf("template %q is not global-scope (project_id = %s)", rec.Key, *rec.ProjectID)
		}
		if rec.Key != prompt.NormalizeKey(rec.Key) {
			t.Errorf("key %q is not normalized", rec.Key)
		}
		if seen[rec.Key] {
			t.Errorf("duplicate key %q", rec.Key)
		}
		seen[rec.Key] = true
		if !prompt.PromptPurpose(rec.Purpose).Known() {
			t.Errorf("purpose %q is not a known WBS purpose", rec.Purpose)
		}
		if !rec.Enabled {
			t.Errorf("template %q not enabled", rec.Key)
		}
		v, err := svc.CurrentVersion(ctx, rec.ID)
		if err != nil {
			t.Fatalf("CurrentVersion(%s): %v", rec.Key, err)
		}
		if v == nil || v.Version != 1 {
			t.Fatalf("template %q version = %v, want v1", rec.Key, v)
		}
		if v.Content == "" || v.ContentHash == "" {
			t.Fatalf("template %q v1 content/hash empty", rec.Key)
		}
		if rec.Name == "" {
			t.Errorf("template %q has empty name", rec.Key)
		}
	}
	for _, k := range want {
		if !seen[k] {
			t.Errorf("WBS 8.2 default key %q not seeded", k)
		}
	}
}

// T8.2.2 — Seeding idempotent: a second call finds the existing global
// templates by scoped key and leaves the template rows and their version
// rows byte-unchanged (no new rows, no new version rows).
func TestP812SeedIdempotent(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	svc := p812Service(t, h)
	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("SeedDefaults: %v", err)
	}
	beforeSig := p812Signature(t, h, ctx)
	var tplCount, verCount int
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_templates WHERE project_id IS NULL`, &tplCount); err != nil {
		t.Fatal(err)
	}
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_template_versions`, &verCount); err != nil {
		t.Fatal(err)
	}
	if tplCount != p812Seeded || verCount != p812Seeded {
		t.Fatalf("after first seed: templates = %d, versions = %d, want %d/%d", tplCount, verCount, p812Seeded, p812Seeded)
	}

	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("second SeedDefaults: %v", err)
	}
	if afterSig := p812Signature(t, h, ctx); afterSig != beforeSig {
		t.Fatalf("second seed mutated the global templates:\nbefore = %s\nafter  = %s", beforeSig, afterSig)
	}
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_templates WHERE project_id IS NULL`, &tplCount); err != nil {
		t.Fatal(err)
	}
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_template_versions`, &verCount); err != nil {
		t.Fatal(err)
	}
	if tplCount != p812Seeded || verCount != p812Seeded {
		t.Fatalf("after second seed: templates = %d, versions = %d, want %d/%d (idempotency violated)", tplCount, verCount, p812Seeded, p812Seeded)
	}
	// Version rows must remain exactly the v1 rows with unchanged hashes.
	var hashes string
	if err := h.DBScan(ctx, `SELECT coalesce(string_agg(content_hash, ',' ORDER BY template_id::text), '') FROM prompt_template_versions`, &hashes); err != nil {
		t.Fatal(err)
	}
	list, err := svc.ListGlobal(ctx)
	if err != nil {
		t.Fatal(err)
	}
	for _, rec := range list {
		v, err := svc.CurrentVersion(ctx, rec.ID)
		if err != nil {
			t.Fatal(err)
		}
		if v == nil || v.Version != 1 || v.ContentHash == "" {
			t.Fatalf("template %q version row changed after re-seed: %+v", rec.Key, v)
		}
	}
}

// T8.2.3 — Required states resolve a template: every state of the default
// machine that carries a prompt-template reference (service.defaultStateSpecs,
// the WBS 6.7 source) resolves via GetByKey at global scope to a seeded
// template; control/terminal states carry no reference.
func TestP812RequiredStatesResolve(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	svc := p812Service(t, h)
	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("SeedDefaults: %v", err)
	}
	referenced := 0
	for _, spec := range service.DefaultStateTemplateRefs {
		rec, err := svc.GetByKeyGlobal(ctx, spec.TemplateKey)
		if err != nil {
			t.Fatalf("state %q -> key %q does not resolve globally: %v", spec.StateKey, spec.TemplateKey, err)
		}
		if rec.Key != prompt.NormalizeKey(spec.TemplateKey) {
			t.Fatalf("state %q resolved to key %q, want %q", spec.StateKey, rec.Key, prompt.NormalizeKey(spec.TemplateKey))
		}
		referenced++
	}
	if referenced != 7 {
		t.Fatalf("required-state references = %d, want 7 (WBS 8.2 required-state set)", referenced)
	}
	// Non-vacuity: the reference table must not list a state without a key.
	for _, spec := range service.DefaultStateTemplateRefs {
		if spec.StateKey == "" || spec.TemplateKey == "" {
			t.Fatalf("malformed reference %+v", spec)
		}
	}
}

// T8.2.4 — Project may override a default: a project-scoped template with a
// default key is created cleanly (the P8-10 scoped uniqueness allows it).
func TestP812ProjectOverride(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	svc := p812Service(t, h)
	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("SeedDefaults: %v", err)
	}
	projectID := p812ProjectRow(t, h)
	key := service.DefaultTemplateKeys[3] // IMPLEMENT_WORK_UNIT
	rec := p810Rec(t, &projectID, key, prompt.PurposeImplementation)
	pool := h.App.DB().Raw()
	trepo := dbrepo.NewPromptTemplateRepository(pool)
	if err := trepo.Create(ctx, rec); err != nil {
		t.Fatalf("project-scoped override create failed: %v", err)
	}
	got, err := trepo.GetByKey(ctx, &projectID, key)
	if err != nil {
		t.Fatalf("GetByKey(project scope): %v", err)
	}
	if got.ID != rec.ID {
		t.Fatalf("override read back id %s, want %s", got.ID, rec.ID)
	}
}

// T8.2.5 — Global default unaffected by project override: the global
// template row is byte-unchanged after the project-scoped override exists.
func TestP812GlobalUnaffectedByOverride(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	svc := p812Service(t, h)
	if err := svc.SeedDefaults(ctx); err != nil {
		t.Fatalf("SeedDefaults: %v", err)
	}
	beforeSig := p812Signature(t, h, ctx)

	projectID := p812ProjectRow(t, h)
	key := service.DefaultTemplateKeys[3] // IMPLEMENT_WORK_UNIT
	pool := h.App.DB().Raw()
	trepo := dbrepo.NewPromptTemplateRepository(pool)
	rec := p810Rec(t, &projectID, key, prompt.PurposeImplementation)
	if err := trepo.Create(ctx, rec); err != nil {
		t.Fatalf("project-scoped override create failed: %v", err)
	}

	afterSig := p812Signature(t, h, ctx)
	if afterSig != beforeSig {
		t.Fatalf("global template rows changed after project override:\nbefore = %s\nafter  = %s", beforeSig, afterSig)
	}
	// Global and project rows are distinct.
	global, err := trepo.GetByKey(ctx, nil, key)
	if err != nil {
		t.Fatal(err)
	}
	if global.ID == rec.ID {
		t.Fatal("global and override rows are the same row")
	}
}

// Concurrency: parallel SeedDefaults calls (the advisory-locked path) commit
// exactly the 9 rows + 9 v1 version rows; the -race gate covers the op.
func TestP812ConcurrentSeed(t *testing.T) {
	h := NewHarness(t)
	ctx := context.Background()
	var wg sync.WaitGroup
	errs := make(chan error, 5)
	for i := 0; i < 5; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if err := p812Service(t, h).SeedDefaults(ctx); err != nil {
				errs <- err
			}
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Fatalf("concurrent SeedDefaults: %v", err)
	}
	var tplCount, verCount int
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_templates WHERE project_id IS NULL`, &tplCount); err != nil {
		t.Fatal(err)
	}
	if err := h.DBScan(ctx, `SELECT count(*) FROM prompt_template_versions`, &verCount); err != nil {
		t.Fatal(err)
	}
	if tplCount != p812Seeded || verCount != p812Seeded {
		t.Fatalf("after concurrent seeds: templates = %d, versions = %d, want %d/%d", tplCount, verCount, p812Seeded, p812Seeded)
	}
}

