package worker

import (
	"fmt"
	"time"
)

// ConcurrentSendPolicy decides what a second send on a busy
// single-request session does (WBS 12.56).
type ConcurrentSendPolicy string

// Concurrent-send policies.
const (
	SendReject ConcurrentSendPolicy = "REJECT"
	SendWait   ConcurrentSendPolicy = "WAIT"
)

// ResponseFormat is how the worker formats its replies to commands.
type ResponseFormat string

// Response formats.
const (
	FormatMarkdown ResponseFormat = "MARKDOWN"
	FormatXML      ResponseFormat = "XML"
	FormatKeyValue ResponseFormat = "KEY_VALUE"
)

// ResponseFormats lists the response formats in display order.
var ResponseFormats = []ResponseFormat{FormatMarkdown, FormatXML, FormatKeyValue}

// Valid reports whether f is a known response format.
func (f ResponseFormat) Valid() bool {
	return f == FormatMarkdown || f == FormatXML || f == FormatKeyValue
}

// KeyValueGrammar is the GBNF grammar of the key:value reply format: a
// summary line, then one or more blocker lines ("blocker: none" when there
// is no blocker). It is sent with every request of a key:value project so a
// grammar-constrained model can only produce a well-formed reply.
const KeyValueGrammar = `# GBNF grammar generated by Overseer: the key:value reply format.
# A reply is one "summary:" line, then one or more "blocker:" lines
# ("blocker: none" when there is no blocker).
root    ::= summary blocker+
summary ::= "summary: " value "\n"
blocker ::= "blocker: " value "\n"
value   ::= [^\n]+
`

// Grammar returns the GBNF grammar constraining replies in format f, or ""
// when the format has none (only key:value has one).
func (f ResponseFormat) Grammar() string {
	if f == FormatKeyValue {
		return KeyValueGrammar
	}
	return ""
}

// OrDefault returns f, or Markdown when f is unset.
func (f ResponseFormat) OrDefault() ResponseFormat {
	if f == "" {
		return FormatMarkdown
	}
	return f
}

// Label is the operator-facing name of the format.
func (f ResponseFormat) Label() string {
	switch f {
	case FormatXML:
		return "XML"
	case FormatKeyValue:
		return "key:value"
	}
	return "Markdown"
}

// Settings are the per-project worker session settings (WBS 12.22/12.56/
// 12.57).
type Settings struct {
	SessionPolicy  SessionPolicy
	ConcurrentSend ConcurrentSendPolicy
	// Lease is the session dispatch lease TTL (renewed while in flight).
	Lease time.Duration
	// Wait bounds a WAIT-policy send waiting for the session.
	Wait time.Duration
	// ResponseFormat is the required formatting of the worker's replies;
	// unset means Markdown.
	ResponseFormat ResponseFormat
}

// DefaultSettings: single active session, reject concurrent sends, 60 s
// lease, Markdown replies.
func DefaultSettings() Settings {
	return Settings{SessionPolicy: DefaultSessionPolicy, ConcurrentSend: SendReject, Lease: 60 * time.Second, Wait: 30 * time.Second,
		ResponseFormat: FormatMarkdown}
}

// Validate checks the settings.
func (s Settings) Validate() error {
	switch {
	case !s.SessionPolicy.Valid():
		return fmt.Errorf("worker: invalid session policy %q", s.SessionPolicy)
	case s.ConcurrentSend != SendReject && s.ConcurrentSend != SendWait:
		return fmt.Errorf("worker: invalid concurrent send policy %q", s.ConcurrentSend)
	case s.Lease < time.Second:
		return fmt.Errorf("worker: lease must be at least 1s")
	case s.Wait < 0:
		return fmt.Errorf("worker: wait must not be negative")
	case s.ResponseFormat != "" && !s.ResponseFormat.Valid():
		return fmt.Errorf("worker: invalid response format %q", s.ResponseFormat)
	}
	return nil
}
