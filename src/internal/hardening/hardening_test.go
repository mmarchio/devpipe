// P16-22 (16.88).
func TestP1622PassLifecycle(t *testing.T) {
	for _, s := range AllPassStatuses() {
		if got, err := ParsePassStatus(string(s)); err != nil || got != s {
			t.Fatal(s)
		}
	}
	p, err := NewPass(uuid.New(), uuid.New(), 1, time.Now())
	if err != nil || p.Status != PassPending || p.Round != 1 || p.Version != 1 {
		t.Fatalf("%+v %v", p, err)
	}
	if _, err := NewPass(uuid.Nil, uuid.New(), 1, time.Now()); err == nil {
		t.Fatal("nil execution")
	}
	ok := [][2]PassStatus{{PassPending, PassAnalyzing}, {PassAnalyzing, PassPlanning}, {PassPlanning, PassExecuting},
		{PassExecuting, PassValidating}, {PassValidating, PassAnalyzing}, {PassAnalyzing, PassDone}, {PassExecuting, PassRecoveryRequired},
		{PassRecoveryRequired, PassExecuting}, {PassValidating, PassFailed}}
	for _, e := range ok {
		if err := ValidateTransition(e[0], e[1]); err != nil {
			t.Fatalf("%v rejected", e)
		}
	}
	for _, e := range [][2]PassStatus{{PassDone, PassAnalyzing}, {PassPending, PassExecuting}, {PassFailed, PassRecoveryRequired}, {PassRecoveryRequired, PassDone}} {
		if !errors.Is(ValidateTransition(e[0], e[1]), ErrIllegalPassTransition) {
			t.Fatalf("%v allowed", e)
		}
	}
}

