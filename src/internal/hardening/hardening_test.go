// P16-31 (16.103–16.105).
func TestP1631ImportGraph(t *testing.T) {
	g := NewImportGraph([]PackageInfo{{ImportPath: "A", Imports: []string{"B"}}, {ImportPath: "B", Imports: []string{"C"}}, {ImportPath: "C"}})
	if g.FindCycle() != nil {
		t.Fatal("acyclic graph has cycle")
	}
	direct := g.Prospective("shared", []string{"A"}, []string{"A"})
	if c := direct.FindCycle(); c == nil || c[0] != c[len(c)-1] {
		t.Fatalf("direct cycle missed: %v", c)
	}
	// A → shared → B → C → A
	g2 := NewImportGraph([]PackageInfo{{ImportPath: "B", Imports: []string{"C"}}, {ImportPath: "C", Imports: []string{"A"}}, {ImportPath: "A"}})
	c := g2.Prospective("shared", []string{"B"}, []string{"A"}).FindCycle()
	if strings.Join(c, ">") != "A>shared>B>C>A" {
		t.Fatalf("transitive cycle: %v", c)
	}
	if len(g.Imports("A")) != 1 || g.Clone().FindCycle() != nil {
		t.Fatal("clone")
	}
}

