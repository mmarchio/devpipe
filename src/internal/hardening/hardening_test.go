// P16-34 (16.108, 16.109): every group classified, precedence.
func TestP1634Classify(t *testing.T) {
	d := &Destination{ImportPath: "m/stringutil", Symbol: "F"}
	cases := []struct {
		c    Checks
		want Classification
	}{
		{Checks{Destination: d}, ClassSafe},
		{Checks{Destination: d, SideEffect: "x", Signature: "y"}, ClassUnsafeSideEffect},
		{Checks{Destination: d, Signature: "y"}, ClassUnsafeTypeDependency},
		{Checks{Destination: d, ReceiverVerdict: ReceiverRequired, Receiver: "r"}, ClassUnsafeTypeDependency},
		{Checks{Destination: d, LocalDeps: "l"}, ClassUnsafeTypeDependency},
		{Checks{Destination: d, ReceiverVerdict: ReceiverNoSharedAb, Receiver: "r"}, ClassRequiresReview},
		{Checks{}, ClassRequiresReview},
		{Checks{Destination: d, Layer: "l", Cycle: []string{"a", "a"}}, ClassUnsafeArchitecture},
		{Checks{Destination: d, Cycle: []string{"a", "s", "a"}, LowValue: "v"}, ClassUnsafeImportCycle},
		{Checks{Destination: d, LowValue: "v"}, ClassLowValue},
		{Checks{Destination: d, Retained: "accepted"}, ClassLowValue},
	}
	for i, c := range cases {
		got, why := Classify(c.c)
		if got != c.want || why == "" {
			t.Fatalf("case %d: %s %q want %s", i, got, why, c.want)
		}
	}
	// Assess composes the checks: the A → shared → B → A case is unsafe.
	a, b := fn("A", "normalize", "X"), fn("B", "normalize", "X")
	a.Imports, b.Imports = []string{"strings", "m/B"}, []string{"strings"}
	g := GroupByFingerprint([]FunctionInfo{a, b})[0]
	graph := NewImportGraph([]PackageInfo{{ImportPath: "m/A", Imports: []string{"m/B"}}, {ImportPath: "m/B"}})
	ctx := AnalysisContext{ModulePath: "m", NewBase: "internal", Graph: graph, Settings: DefaultSettings()}
	// shared imports what the first member body imports (m/B) — and m/B
	// will import shared: B → shared → B.
	_, cl, why := Assess(g, ctx)
	if cl != ClassUnsafeImportCycle {
		t.Fatalf("%s %s", cl, why)
	}
}

