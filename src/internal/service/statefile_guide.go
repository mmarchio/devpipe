// Team files of the statefile workflow, written to
// <working directory>/statefiles when an execution starts: one file per
// role of the workflow (its system prompt and instructions, as captured in
// the execution's configuration snapshot) and HERMES.md — the workflow
// rules, the commands and the MCP tools the team reports through. They
// are generated projections: the roles are edited in the console, not in
// these files, and no workflow state is read back from them.

// GuideFile is the generated workflow guide.
const GuideFile = wbs.StatefilesDir + "/HERMES.md"

// RoleFile is the generated file of a role.
func RoleFile(key string) string { return wbs.StatefilesDir + "/" + key + ".md" }

// statefileMachine reports whether the machine is the statefile workflow.
func statefileMachine(m state.StateMachineSnapshot) bool {
	for _, s := range m.States {
		if s.Key == "ACCEPTANCE_CHECK" {
			return true
		}
	}
	return false
}

// writeTeamFiles writes the role files and HERMES.md for a statefile
// workflow execution (nothing for other workflows).
func (s *BootstrapService) writeTeamFiles(ctx context.Context, projectID uuid.UUID, content execution.ConfigurationContent) error {
	if !statefileMachine(content.StateMachine) {
		return nil
	}
	cwd := content.WorkingDirectory
	roles := map[string]role.RoleSnapshot{}
	for _, r := range content.Roles {
		roles[r.RoleKey] = r
	}
	keys := make([]string, 0, len(roles))
	for k := range roles {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if err := writeStatefile(cwd, RoleFile(k), renderRoleFile(roles[k])); err != nil {
			return fmt.Errorf("write %s: %w", RoleFile(k), err)
		}
	}
	commands, err := s.stateCommands(ctx, content)
	if err != nil {
		return err
	}
	if err := writeStatefile(cwd, GuideFile, RenderMCPGuide(content.StateMachine, keys, commands)); err != nil {
		return fmt.Errorf("write %s: %w", GuideFile, err)
	}
	return nil
}

// writeStatefile writes a generated team file (HERMES.md, a role file) to
// rel under the working directory (creating directories) unless it
// already holds exactly that content.
func writeStatefile(cwd, rel, content string) error {
	// Both the directory and the file are confined to the working
	// directory (symlinks resolved) before anything is written.
	dir, err := statefile.SafeRelPath(cwd, filepath.Dir(rel))
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	abs, err := statefile.SafeRelPath(cwd, rel)
	if err != nil {
		return err
	}
	if cur, err := os.ReadFile(abs); err == nil && bytes.Equal(cur, []byte(content)) {
		return nil
	}
	tmp := abs + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, abs)
}

// stateCommands returns each command state's command as shown to the
// team: its captured CMD_ template with the values as placeholders.
func (s *BootstrapService) stateCommands(ctx context.Context, content execution.ConfigurationContent) (map[string]string, error) {
	out := map[string]string{}
	if s.d.States == nil || s.d.TemplateVers == nil {
		return out, nil
	}
	m := content.StateMachine
	recs, err := s.d.States.ListByMachine(ctx, m.MachineID, m.Version)
	if err != nil {
		return nil, translate(err)
	}
	for _, rec := range recs {
		if !execution.IsCommandTemplate(rec.PromptTemplate) {
			continue
		}
		for _, t := range content.PromptTemplates {
			if t.Key != rec.PromptTemplate {
				continue
			}
			v, err := s.d.TemplateVers.GetVersion(ctx, t.TemplateID, t.Version)
			if err != nil {
				return nil, fmt.Errorf("command template %s: %w", t.Key, err)
			}
			out[rec.Key] = strings.NewReplacer("{{command.phase}}", "<N>", "{{command.task}}", "<KEY>", "{{command.skill}}", "<project>-output-format").Replace(strings.TrimSpace(v.Content))
		}
	}
	return out, nil
}

// renderRoleFile renders one role: its system prompt, then its
// instructions in order.
func renderRoleFile(r role.RoleSnapshot) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", r.RoleKey)
	fmt.Fprintf(&b, "<!-- Generated by the overseer from role %s v%d. Edit the role in the overseer console; this file is rewritten when an execution starts. -->\n\n", r.RoleKey, r.RoleVersion)
	b.WriteString("Read `statefiles/HERMES.md` first: it defines the workflow, the commands and the MCP tools results are submitted through.\n\n")
	b.WriteString("## ROLE\n\n")
	b.WriteString(strings.TrimSpace(r.SystemPrompt.Content))
	b.WriteString("\n")
	for _, in := range r.Instructions {
		name := in.Name
		if name == "" {
			name = in.Key
		}
		fmt.Fprintf(&b, "\n## %s\n\n%s\n", strings.ToUpper(name), strings.TrimSpace(in.Content))
	}
	if len(r.AllowedStates) > 0 {
		states := append([]string(nil), r.AllowedStates...)
		sort.Strings(states)
		fmt.Fprintf(&b, "\n## WORKFLOW STATES\n\n%s\n", strings.Join(states, ", "))
	}
	return b.String()
}

// returnFormat is the reply rule of every command.
const returnFormat = "Reply to each command with a short summary of what was done and any blocker, formatted as the project's output-format skill requires. The reply is stored for the operator but never parsed: " +
	"every result the overseer acts on must be submitted through the overseer MCP server (submit_result) before replying."

// OutputFormatSkillName is the Hermes skill holding a project's required
// response formatting: "<project slug>-output-format".
func OutputFormatSkillName(projectName string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(projectName) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
			dash = false
		} else if b.Len() > 0 && !dash {
			b.WriteByte('-')
			dash = true
		}
	}
	slug := strings.TrimSuffix(b.String(), "-")
	if slug == "" {
		slug = "project"
	}
	return slug + "-output-format"
}

// replyFormat is the reply formatting instruction for a response format
// (the project's worker setting).
func replyFormat(f worker.ResponseFormat) string {
	switch f {
	case worker.FormatXML:
		return "Format every reply as XML: one `<reply>` root element holding a `<summary>` element and one `<blocker>` element per blocker " +
			"(none when there is no blocker), escaping `<`, `>` and `&` in text. For example:\n\n" +
			"```xml\n<reply>\n  <summary>Implemented the parser and its unit tests.</summary>\n</reply>\n```\n"
	case worker.FormatKeyValue:
		return "Format every reply as `key: value` lines, one per line with no other text: a `summary:` line, then one `blocker:` line per blocker " +
			"(`blocker: none` when there is no blocker). For example:\n\n" +
			"```text\nsummary: Implemented the parser and its unit tests.\nblocker: none\n```\n"
	}
	return "Format every reply as Markdown: a short summary paragraph, then a `## Blockers` list (`- None` when there is no blocker). For example:\n\n" +
		"```markdown\nImplemented the parser and its unit tests.\n\n## Blockers\n\n- None\n```\n"
}

// OutputFormatSkill renders the SKILL.md of the project's output-format
// skill: the reply rule in the project's response format and a pre-reply
// checklist — the same rules HERMES.md documents and the overseer enforces.
func OutputFormatSkill(projectName string, format worker.ResponseFormat) string {
	var b strings.Builder
	name := OutputFormatSkillName(projectName)
	fmt.Fprintf(&b, "---\nname: %s\ndescription: Required response formatting for the %s project. "+
		"Load and follow it before replying to any overseer command for this project.\n---\n\n",
		name, strings.ReplaceAll(projectName, "\n", " "))
	fmt.Fprintf(&b, "# %s output format\n\n", projectName)
	b.WriteString("The overseer reads only the results submitted through its MCP server; a missing or rejected result makes it send the " +
		"command again with the problem. Follow these rules to the letter.\n\n")
	b.WriteString("## Replies\n\n" + returnFormat + "\n\n" + replyFormat(format) + "\n")
	b.WriteString("## Before you reply\n\n")
	fmt.Fprintf(&b, "- The reply is formatted as %s, as shown under Replies.\n", format.Label())
	b.WriteString("- When the command expects a result, submit_result was called with the command's token before replying.\n")
	b.WriteString("- Acceptance criteria are never changed after planning, except when the architect is asked to replan the task.\n")
	fmt.Fprintf(&b, "- The rules in `%s` apply; when it and this skill differ, `%s` wins.\n", GuideFile, GuideFile)
	return b.String()
}

// RenderMCPGuide renders HERMES.md (Phase 19): the team reads its context
// and submits every result through the overseer MCP server; no statefile
// is read or written.
func RenderMCPGuide(m state.StateMachineSnapshot, roleKeys []string, commands map[string]string) string {
	rolesOf := map[string]string{}
	for _, st := range m.States {
		rolesOf[st.Key] = strings.Join(st.Roles, ", then ")
	}
	cmd := func(stateKey, fallback string) string {
		if c := commands[stateKey]; c != "" {
			return "`" + c + "`"
		}
		return fallback
	}
	roleFiles := make([]string, 0, len(roleKeys))
	for _, k := range roleKeys {
		roleFiles = append(roleFiles, "`"+RoleFile(k)+"`")
	}
	var b strings.Builder
	b.WriteString("# HERMES — workflow rules\n\n")
	b.WriteString("<!-- Generated by the overseer when an execution starts; do not edit. -->\n\n")
	b.WriteString("The overseer drives this project with one short command per step. The team reads its working context and reports every result " +
		"through the overseer MCP server; the overseer alone decides when a task is done, which task or phase is next, and when work is retried. " +
		"Do not read or write files under `statefiles/` to record workflow state.\n\n")
	b.WriteString("Role files: " + strings.Join(roleFiles, ", ") + " (also `get_role`). Act as the role(s) named for the command.\n\n")
	b.WriteString("Every command is preceded by the prompt `change working directory to <project working directory>`: change to that directory " +
		"and work only inside it. That prompt sent on its own is not a command: change the directory, reply, and do nothing else.\n\n")
	b.WriteString("## MCP tools\n\nEvery command ends with a token: pass it to every tool call. Reporting calls take a new `idempotency_key` each.\n\n")
	b.WriteString("- `get_current_state`, `get_task`, `get_context` (phase WBS, plan, active task), `get_role`, `get_execution_history` — read.\n")
	b.WriteString("- `report_progress`, `report_blocker` — while working.\n")
	b.WriteString("- `submit_result` — the command's result, required before replying when the command expects one.\n")
	b.WriteString("- `request_transition`, `request_retry`, `request_context_reset` — requests; the overseer decides.\n\n")
	b.WriteString("## Commands\n\n| Command | Role | Required result (`submit_result`) |\n|---|---|---|\n")
	fmt.Fprintf(&b, "| %s | %s | None: save the skill given in the command and follow it. |\n", cmd("SKILL", "create the <project>-output-format skill"), rolesOf["SKILL"])
	fmt.Fprintf(&b, "| %s | %s | PLAN: status COMPLETE and `plan` with every atomic, testable task of the phase, from the phase WBS (`get_context`). |\n",
		cmd("PLAN", "plan phase <N>"), rolesOf["PLAN"])
	fmt.Fprintf(&b, "| %s | %s | ACCEPTANCE: COMPLETE accepts and archives the finished task; the overseer loads the next one. |\n",
		cmd("ACCEPTANCE", "have the project manager perform acceptance tasks"), rolesOf["ACCEPTANCE"])
	fmt.Fprintf(&b, "| %s / %s | %s | IMPLEMENT: COMPLETE, INCOMPLETE, BLOCKED or FAILED, with a summary of the changes. |\n",
		cmd("IMPLEMENT", "implement task <KEY>"), cmd("CONTINUE", "continue"), rolesOf["IMPLEMENT"])
	fmt.Fprintf(&b, "| %s | %s | TEST: `criteria_met` (one true/false per acceptance check, in order); COMPLETE only when all are met. |\n",
		cmd("TEST", "test task <KEY>"), rolesOf["TEST"])
	fmt.Fprintf(&b, "| %s | %s | PLAN: exactly the replanned task, its key, kind and dependencies unchanged. |\n",
		cmd("REPLAN", "have the architect replan task <KEY>"), rolesOf["REPLAN"])
	b.WriteString("\nThe overseer validates every task itself before acceptance. A result given only in the reply is not read.\n")
	return b.String()
}
